// Read-only desktop acceptance for provider routing and historical CGAL evidence.
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { join } from 'node:path'

const require = createRequire(import.meta.url)
const { chromium } = require(join(import.meta.dirname, '..', 'DevShell', 'ui', 'dev-ui-react', 'node_modules', 'playwright-core'))
const browser = await chromium.connectOverCDP(process.env.DEVSHELL_CDP_URL || 'http://127.0.0.1:9239')
try {
  const page = browser.contexts().flatMap(context => context.pages()).find(item => item.url().includes('app.local'))
  assert.ok(page, 'DevShell desktop page must be running')
  page.setDefaultTimeout(30_000)
  await page.getByText('RUNTIMES / Scientific', { exact: true }).click()
  const main = page.getByRole('main', { name: 'Scientific Runtimes' })
  const detail = main.getByRole('region', { name: /runtime details/ })
  const nav = main.getByRole('navigation', { name: 'Scientific runtime sections' })
  const choose = async name => main.locator('.scientific-runtime-item').filter({ hasText: name }).first().click()
  const sectionNames = async () => nav.getByRole('button').allTextContents()

  await choose('CGAL')
  assert.ok((await sectionNames()).includes('Boolean'))
  assert.ok((await sectionNames()).includes('Catalog'))
  assert.ok((await sectionNames()).includes('Artifacts'))
  await nav.getByRole('button', { name: 'Catalog' }).click()
  assert.equal(await detail.locator('.scientific-test-catalog-card').count(), 2)
  assert.equal(await detail.getByText('SageMath installation').count(), 0)
  await nav.getByRole('button', { name: 'History' }).click()
  const history = main.getByRole('region', { name: 'Scientific run history' })
  await history.getByRole('button', { name: /Load history|Refresh history/ }).click()
  await history.getByLabel('History runtime filter').waitFor()
  assert.equal(await history.getByLabel('History runtime filter').inputValue(), 'cgal-win-conda')
  const oldRun = history.locator('tr[data-run-id="17f5513271c449f28904c04b12c77064"]')
  await oldRun.waitFor()
  await oldRun.getByRole('button', { name: 'Result' }).click()
  await history.getByText('Native worker comparison: PASS / 35/35').waitFor()

  await choose('VTK')
  assert.ok(!(await sectionNames()).includes('Boolean'))
  assert.ok((await sectionNames()).includes('Catalog'))
  assert.ok((await sectionNames()).includes('Artifacts'))
  await nav.getByRole('button', { name: 'Catalog' }).click()
  assert.equal(await detail.locator('.scientific-test-catalog-card').count(), 2)
  assert.equal(await detail.getByText('Exact factorization').count(), 0)
  await nav.getByRole('button', { name: 'Integration' }).click()
  assert.match(await detail.innerText(), /VTK \/ MATH3D integration[\s\S]*Not configured/)
  assert.equal(await detail.getByRole('button', { name: 'Prepare & Run' }).count(), 0)
  await nav.getByRole('button', { name: 'History' }).click()
  assert.equal(await history.getByLabel('History runtime filter').inputValue(), 'vtk-win-conda')
  assert.equal(await history.getByText('Native worker comparison: PASS / 35/35').count(), 0)
  assert.equal(await history.getByText('Prepare comparable runs').count(), 0)

  for (const [name, id] of [['Gmsh', 'gmsh-win-conda'], ['Python / SciPy', 'python-win-conda']]) {
    await choose(name)
    const names = await sectionNames()
    assert.ok(!names.includes('Boolean') && !names.includes('Artifacts') && !names.includes('Catalog'))
    await nav.getByRole('button', { name: 'Tests' }).click()
    await main.getByRole('region', { name: `${name} capability coverage` }).waitFor()
    assert.equal(await detail.getByRole('button', { name: 'Prepare & Run' }).count(), 0)
    await nav.getByRole('button', { name: 'History' }).click()
    assert.equal(await history.getByLabel('History runtime filter').inputValue(), id)
  }

  await choose('SageMath')
  assert.match(await detail.innerText(), /Not configured/)
  assert.ok(!(await sectionNames()).includes('Tests'))
  await main.getByLabel('Scientific execution environment').selectOption('wsl')
  await choose('SageMath')
  assert.ok((await sectionNames()).includes('Commands'))
  assert.ok((await sectionNames()).includes('Catalog'))
  assert.ok(!(await sectionNames()).includes('Boolean'))
  await nav.getByRole('button', { name: 'Catalog' }).click()
  assert.equal(await detail.locator('.scientific-test-catalog-card').count(), 2)
  assert.equal(await detail.getByText('CGAL validation matrix').count(), 0)
  await nav.getByRole('button', { name: 'Tests' }).click()
  await main.getByRole('region', { name: 'SageMath capability coverage' }).waitFor()
  assert.equal(await detail.getByRole('button', { name: 'Run mesh recipe' }).count(), 0)
  await nav.getByRole('button', { name: 'History' }).click()
  assert.equal(await history.getByLabel('History runtime filter').inputValue(), 'sage-wsl')
  await main.getByLabel('Scientific execution environment').selectOption('docker')
  assert.match(await detail.innerText(), /Not configured/)
  assert.ok(!(await sectionNames()).includes('Tests'))
  console.log('PASS: five runtime views, backend state, scoped history, and historical CGAL 35/35 result')
} finally {
  await browser.close()
}
